export function SectionHeading({
  eyebrow,
  title,
  description,
  align = "center",
}: {
  eyebrow?: string;
  title: string;
  description?: string;
  align?: "center" | "left";
}) {
  return (
    <div className={align === "center" ? "mx-auto max-w-2xl text-center" : "max-w-2xl"}>
      {eyebrow ? (
        <p className="text-xs font-semibold tracking-[0.28em] text-cyan uppercase">{eyebrow}</p>
      ) : null}
      <h2 className="mt-3 text-2xl font-bold tracking-wide uppercase sm:text-3xl">
        <span className="text-pulse">{title}</span>
      </h2>
      {description ? (
        <p className="mt-4 text-base leading-relaxed text-muted-foreground">{description}</p>
      ) : null}
    </div>
  );
}